"""Generate Sources/HutchbarCore/ModelPriceTable.swift from Resources/model-prices.json.

The price list (schema 1) comes from Vorssaint (GPL-3.0-or-later,
https://github.com/vorssaint/vorssaint-utils, Resources/agent-prices.json).
Run after updating the JSON:  python3 -I Tools/gen-model-prices.py
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "Resources" / "model-prices.json"
dst = root / "Sources" / "HutchbarCore" / "ModelPriceTable.swift"


def num(value):
    text = repr(float(value))
    return text[:-2] if text.endswith(".0") else text


def opt(model, key):
    return num(model[key]) if key in model else "nil"


def entry(provider, model):
    long = model.get("longContext") or {}
    fields = [
        f'"{model["id"]}"',
        f".{provider}",
        num(model["input"]),
        num(model["output"]),
        num(model["cacheRead"]),
        opt(model, "cacheWrite"),
        opt(model, "cacheWriteLong"),
        opt(model, "fastMultiplier"),
        num(long["above"]) if long else "nil",
        num(long["inputMultiplier"]) if long else "nil",
        num(long["outputMultiplier"]) if long else "nil",
    ]
    return "    .init(" + ", ".join(fields) + "),"


def main():
    data = json.loads(src.read_text())
    if data.get("schema") != 1:
        sys.exit("unsupported price list schema")
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by Tools/gen-model-prices.py from Resources/model-prices.json. Do not edit.",
        "// Price list: Vorssaint (GPL-3.0-or-later), https://github.com/vorssaint/vorssaint-utils",
        "// swiftlint:disable line_length file_length",
        "",
        "extension ModelPriceTable {",
        f'  static let bundledUpdated = "{data["updated"]}"',
        "",
        "  /// id, provider, input, output, cacheRead, cacheWrite, cacheWriteLong, fastMultiplier,",
        "  /// longContext above / inputMultiplier / outputMultiplier. USD per 1M tokens.",
        "  static let bundled: [ModelPriceEntry] = [",
    ]
    for provider in ("claude", "codex"):
        for model in data[provider]["models"]:
            lines.append(entry(provider, model))
    lines += ["  ]", "}", ""]
    dst.write_text("\n".join(lines))
    print(f"wrote {dst.relative_to(root)}")


main()
